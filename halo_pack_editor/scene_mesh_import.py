"""Import an ordinary Blender Mesh as a Halo 2.x native OBJ primitive.

The native Halo loader intentionally accepts a small OBJ subset.  This bridge
therefore writes its own deterministic OBJ instead of relying on Blender's
general exporter: evaluated geometry is reduced to textured triangles, all
coordinates are converted back to Minecraft space, and unsupported OBJ/MTL
features never enter the resource pack.
"""

from __future__ import annotations

